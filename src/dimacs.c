#include "sat.h"

#include <ctype.h>
#include <errno.h>
#include <limits.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef struct { FILE *file; size_t line; int line_start; } Lexer;

/* Read whitespace-separated tokens; comment lines may appear throughout a file. */
static int next_token(Lexer *lexer, char token[64]) {
    int c;
    for (;;) {
        c = fgetc(lexer->file);
        if (c == EOF) return ferror(lexer->file) ? -1 : 0;
        if (c == '\n') { ++lexer->line; lexer->line_start = 1; continue; }
        if (isspace((unsigned char)c)) continue;
        if (c == 'c' && lexer->line_start) {
            while ((c = fgetc(lexer->file)) != '\n' && c != EOF) {}
            if (c == '\n') { ++lexer->line; lexer->line_start = 1; }
            continue;
        }
        break;
    }
    lexer->line_start = 0;
    size_t count = 0;
    do {
        if (count < 63) token[count] = (char)c;
        ++count;
        c = fgetc(lexer->file);
    } while (c != EOF && !isspace((unsigned char)c));
    if (c == '\n') { ++lexer->line; lexer->line_start = 1; }
    token[count < 63 ? count : 63] = '\0';
    return count > 63 || ferror(lexer->file) ? -1 : 1;
}

static int parse_count(const char *token, size_t *value) {
    if (!isdigit((unsigned char)token[0])) return 0;
    char *end;
    errno = 0;
    unsigned long long number = strtoull(token, &end, 10);
    if (errno || *end || number > SIZE_MAX) return 0;
    *value = (size_t)number;
    return 1;
}

int sat_formula_read(SatFormula *formula, const char *path, char *error, size_t error_size) {
    FILE *file = fopen(path, "r");
    if (!file) { snprintf(error, error_size, "Cannot open CNF file: %s", path); return 0; }
    Lexer lexer = {file, 1, 1};
    SatFormula parsed;
    sat_formula_init(&parsed, 0);
    char token[64];
    const char *message = "Expected header: p cnf <variables> <clauses>";
    size_t variables = 0, expected = 0, actual = 0, count = 0, capacity = 0;
    int *literals = NULL, success = 0;
    if (next_token(&lexer, token) != 1 || strcmp(token, "p") != 0) goto done;
    if (next_token(&lexer, token) != 1 || strcmp(token, "cnf") != 0) goto done;
    if (next_token(&lexer, token) != 1 || !parse_count(token, &variables) || variables >= INT_MAX) goto done;
    if (next_token(&lexer, token) != 1 || !parse_count(token, &expected)) goto done;
    parsed.variable_count = (int)variables;
    int read;
    while ((read = next_token(&lexer, token)) == 1) {
        char *end;
        errno = 0;
        long value = strtol(token, &end, 10);
        message = "Invalid literal or variable outside the declared range";
        if (errno || end == token || *end || value < -(long)variables || value > (long)variables) goto done;
        if (value == 0) {
            message = "More clauses than declared in the header";
            if (actual >= expected) goto done;
            message = "Out of memory while reading clauses";
            if (!sat_formula_add(&parsed, literals, count)) goto done;
            ++actual;
            count = 0;
        } else {
            if (count == capacity) {
                size_t new_capacity = capacity ? capacity * 2 : 16;
                message = "Clause is too large or memory allocation failed";
                if (new_capacity < capacity || new_capacity > SIZE_MAX / sizeof(int)) goto done;
                int *new_literals = realloc(literals, new_capacity * sizeof(*literals));
                if (!new_literals) goto done;
                literals = new_literals;
                capacity = new_capacity;
            }
            literals[count++] = (int)value;
        }
    }
    message = "Read failure or oversized token";
    if (read < 0) goto done;
    message = "Every clause must end with 0";
    if (count) goto done;
    message = "Clause count does not match the header";
    if (actual != expected) goto done;
    sat_formula_free(formula);
    *formula = parsed;
    sat_formula_init(&parsed, 0);
    success = 1;
done:
    if (!success) snprintf(error, error_size, "CNF near line %zu: %s", lexer.line, message);
    free(literals);
    sat_formula_free(&parsed);
    fclose(file);
    return success;
}

int sat_formula_write(const SatFormula *formula, const char *path) {
    FILE *file = fopen(path, "w");
    if (!file) return 0;
    fprintf(file, "c Generated by Sudoku SAT\np cnf %d %zu\n", formula->variable_count, formula->clause_count);
    for (size_t i = 0; i < formula->clause_count; ++i) {
        for (size_t j = 0; j < formula->clauses[i].count; ++j) fprintf(file, "%d ", formula->clauses[i].literals[j]);
        fputs("0\n", file);
    }
    int success = !ferror(file);
    if (fclose(file) != 0) success = 0;
    return success;
}

int sat_result_write(const SatResult *result, const char *path) {
    if (result->status == SAT_ERROR) return 0;
    FILE *file = fopen(path, "w");
    if (!file) return 0;
    fprintf(file, "s %d\n", result->status == SAT_SAT ? 1 : 0);
    if (result->status == SAT_SAT) {
        fputs("v ", file);
        for (int i = 1; i <= result->variable_count; ++i) fprintf(file, "%d ", result->values[i] > 0 ? i : -i);
        fputs("0\n", file);
    }
    fprintf(file, "t %.3f\n", result->stats.milliseconds);
    int success = !ferror(file);
    if (fclose(file) != 0) success = 0;
    return success;
}
